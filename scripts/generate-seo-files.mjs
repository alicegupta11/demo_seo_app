/**
 * Writes public/robots.txt and public/sitemap.xml from src/seo/routes.js so the
 * crawler-facing files can never drift from the app's real routes.
 *
 * Runs automatically before `npm run build`, or on demand: npm run seo:generate
 */
import { mkdir, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

import { DEFAULT_SITE_URL, privateRoutes, publicRoutes } from '../src/seo/routes.js'

const projectRoot = join(dirname(fileURLToPath(import.meta.url)), '..')
const publicDir = join(projectRoot, 'public')

const siteUrl = (process.env.VITE_SITE_URL || DEFAULT_SITE_URL).replace(/\/+$/, '')
const lastmod = new Date().toISOString().slice(0, 10)

/**
 * Crawlers denied the whole site: AI training/answer bots, plus search engines
 * this demo has no audience in. Lives here rather than in src/seo/routes.js so
 * the list never reaches the browser bundle.
 */
const blockedCrawlers = [
  'AI2Bot',
  'Amazonbot',
  'anthropic-ai',
  'Bytespider',
  'CCBot',
  'ChatGPT-User',
  'ClaudeBot',
  'Claude-Web',
  'DuckAssistBot',
  'GPTBot',
  'Google-Extended',
  'Meta-ExternalAgent',
  'Meta-ExternalFetcher',
  'MistralAI',
  'OAI-SearchBot',
  'PerplexityBot',
  'YouBot',
  'Baiduspider',
  'YandexBot',
]

function absolute(path) {
  return path === '/' ? `${siteUrl}/` : `${siteUrl}${path}`
}

function buildRobotsTxt() {
  const disallowLines = privateRoutes.map((route) => `Disallow: ${route.path}`).join('\n')
  const blockedAgentLines = blockedCrawlers.map((agent) => `User-agent: ${agent}`).join('\n')

  return `# robots.txt for ${siteUrl}
# Generated by scripts/generate-seo-files.mjs — edit src/seo/routes.js instead.

${blockedAgentLines}
Disallow: /

User-agent: *
Allow: /
${disallowLines}

# Keep crawlers out of build assets that carry no standalone value.
Disallow: /assets/

Sitemap: ${siteUrl}/sitemap.xml
`
}

function buildSitemapXml() {
  const urls = publicRoutes
    .map((route) =>
      [
        '  <url>',
        `    <loc>${absolute(route.path)}</loc>`,
        `    <lastmod>${lastmod}</lastmod>`,
        `    <changefreq>${route.changefreq}</changefreq>`,
        `    <priority>${route.priority.toFixed(1)}</priority>`,
        '  </url>',
      ].join('\n'),
    )
    .join('\n')

  return `<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by scripts/generate-seo-files.mjs — edit src/seo/routes.js instead. -->
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${urls}
</urlset>
`
}

await mkdir(publicDir, { recursive: true })
await Promise.all([
  writeFile(join(publicDir, 'robots.txt'), buildRobotsTxt(), 'utf8'),
  writeFile(join(publicDir, 'sitemap.xml'), buildSitemapXml(), 'utf8'),
])

console.log(`[seo] site URL: ${siteUrl}`)
console.log(`[seo] sitemap.xml: ${publicRoutes.length} public URL(s)`)
console.log(`[seo] robots.txt: ${privateRoutes.length} private path(s) disallowed`)
